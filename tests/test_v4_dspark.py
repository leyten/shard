# ── 8. the end-to-end bet ────────────────────────────────────────────────────────────────────────

def _greedy_stream(args, ids, n):
    """The truth: `n` greedy tokens from a fresh oracle, positions PROMPT..PROMPT+n-1."""
    ref = REFCPU.build_oracle(args, SEED)
    tok, _, _ = ref(ids)
    out = [int(tok)]
    for i in range(ids.shape[1], ids.shape[1] + n - 1):
        tok, _, _ = ref(tok.unsqueeze(1), i)
        out.append(int(tok))
    return out


def _rich_ids(args, n):
    """A prompt whose greedy stream is non-constant ON THIS PLATFORM, richest of a fixed seed list.

    The stream's token VALUES are platform arithmetic: the seed that gives one box 4+ distinct
    tokens gave CI's BLAS 3 (bf16 rounds differently at toy scale), and a CONSTANT stream would
    make a stream-equality assertion vacuous — any misalignment emits the same constant. The parity
    bar itself is within-platform, so any non-constant stream carries it; searching a fixed list
    keeps the choice deterministic per box and loud when no candidate qualifies."""
    best = None
    for seed in (LOOP_SEED, 5, 11, 29, 47):
        ids = _ids(PROMPT, args, seed=seed)
        want = _greedy_stream(args, ids, n)
        k = len(set(want[:GEN]))
        if best is None or k > best[0]:
            best = (k, ids, want)
        if k >= 4:
            break
    assert best[0] >= 2, "every candidate seed yields a CONSTANT greedy stream on this platform"
    return best[1], best[2]


def _rewind(st, ids, committed):
    """Put the stage back to 'has seen the prompt + `committed`'. Step 5's rollback, the slow way.

    `Stage._seek` refuses a rewind today (that is step 5, where `_snapshot`/`_restore` hook in), so
    the test replays from scratch: reset, re-prefill, then feed the committed tokens ONE AT A TIME.
    Deliberately the dumbest possible rewind -- a test that leaned on the rollback seam would be
    grading step 5's design instead of this file's protocol."""
    st.reset()
    st.forward(st.embed(ids), ids, 0)
    for j, t in enumerate(committed):
        one = torch.tensor([[t]], dtype=torch.long)
        st.forward(st.embed(one), one, ids.shape[1] + j)


def _spec_loop(oracle, args, ids, propose):
    """The ring's round, in one process: verify chunk -> accept -> advance -> next chunk.

    `propose(drafts)` picks what actually goes on the wire, so the same loop runs with the real
    drafter and with a perfect one. The verify logits are taken PER POSITION with full_logits=False,
    which is v4_dspark_draft's numerics rule: the same GEMM shape greedy decode uses, so a
    speculated token is bit-identical to the greedy one instead of a 4e-7 argmax coin flip."""
    st, dr, tok = prefilled(oracle, args, ids)
    out = [int(tok)]                          # token at position PROMPT — not fed anywhere yet
    drafts, drafted, rewound = [], 0, 0
    while len(out) < GEN:
        p = ids.shape[1] + len(out) - 1        # absolute position of the chunk's first token
        chunk = torch.tensor([[out[-1]] + list(drafts)], dtype=torch.long)
        drafted += bool(drafts)
        h = st.forward(st.embed(chunk), chunk, p)
        replies = [int(st.logits_all(h[:, j:j + 1], full_logits=False).argmax(-1))
                   for j in range(chunk.shape[1])]
        n, committed = DS.plan_verify_round(drafts, replies)
        taps = st.tail_main_hidden()[:, :n + 1]
        out.extend(committed)
        if len(out) >= GEN:
            break
        got, _ = dr.advance_and_draft(torch.tensor([committed], dtype=torch.long), taps, start_pos=p)
        assert dr.pos == p + n
        drafts = propose(got[0].tolist())
        if n + 1 != chunk.shape[1]:            # a rejected tail was fed and must be un-fed
            _rewind(st, ids, out[:-1])
            rewound += 1
    return out, drafted, rewound


def test_spec_loop_emits_the_greedy_stream(oracle, args):
    """The real drafter, driving real rounds: the emitted stream IS the greedy stream.

    The headline. Lossless is the whole claim of speculative decoding, and every position mistake in
    the protocol -- a tap paired with the wrong token, an advance over the rejected tail, a draft
    block read one column off -- changes this stream and nothing else visible."""
    ids, want = _rich_ids(args, GEN + args.dspark_block_size)
    got, drafted, rewound = _spec_loop(oracle, args, ids, lambda d: d)
    assert got == want[:len(got)], "the speculated stream is not the greedy stream"
    assert len(got) >= GEN
    assert drafted >= 2, "every round after the first must carry a real draft block"
    assert rewound >= 1, "no round was rejected — the rewind path was never exercised"


# ── 9. the ring adapter ──────────────────────────────────────────────────────────────────────────
# RingDrafter is the tail-side protocol: chunk in, (accept length, next block) out. Everything it can
# get wrong is a SLICE — which taps, which tokens, which position — and a wrong slice still produces
# well-shaped drafts. So it is driven against a recorder that captures exactly what it handed the
# drafter, with taps whose VALUES identify their position; the real-weights version of this same
# protocol is the dspark ring in tests/test_v4_pipe.py.

class _RecordingTail:
    """A DSparkTail's contract, recording what it was handed. Nothing computes."""

    def __init__(self, block_size=3, max_seq_len=256, block=(71, 72, 73)):
        self.block_size = block_size
        self.args = type("A", (), {"max_seq_len": max_seq_len})()
        self.block = list(block)
        self.calls = []

    def reset(self):
        self.calls.append(("reset",))

    def prefill(self, pred_ids, main_hidden):
        self.calls.append(("prefill", [int(t) for t in pred_ids], _rows(main_hidden)))

    def advance_and_draft(self, ids_seq, main_hidden_seq, start_pos):
        self.calls.append(("advance", [int(t) for t in torch.as_tensor(ids_seq).reshape(-1)],
                           _rows(main_hidden_seq), start_pos))
        return (torch.tensor([self.block], dtype=torch.long),
                torch.tensor([[0.5] * len(self.block)]))


class _TapStage:
    """A tail Stage's one method the drafter uses, with taps that SAY which position they are: row j
    is the constant j, so a slice taken from the wrong end is visible instead of merely mis-shaped."""

    def __init__(self, s, dim=6):
        self.taps = torch.arange(s, dtype=torch.float32).view(1, s, 1).repeat(1, 1, dim)

    def tail_main_hidden(self):
        return self.taps


def _rows(t):
    """The positions a [1, s, d] tap tensor covers, read back off _TapStage's marking."""
    return [int(r[0]) for r in torch.as_tensor(t)[0]]


def _chunk(ids, start_pos, tokens=None, token=None):
    msg = {"ids": [list(ids)], "start_pos": start_pos}
    out = {"token": token if token is not None else (tokens[-1] if tokens else 0)}
    if tokens is not None:
        out["tokens"] = list(tokens)
    return msg, out


def test_ring_drafter_prefill_round_drafts_nothing():
    """The ring's prefill primes the mtp window over the whole prompt and returns NO draft, so round
    1 is the bare `[cur]` chunk. The token it primes with is the one the model predicted for position
    P — the reply's own `token` — and the taps are all P of the prompt's."""
    tail = _RecordingTail()
    dr = DS.RingDrafter(tail)
    msg, out = _chunk([5, 6, 7, 8], 0, token=99)
    assert dr.on_chunk(msg, _TapStage(4), out) == {}
    assert tail.calls == [("reset",), ("prefill", [99], [0, 1, 2, 3])]


def test_ring_drafter_bare_round_advances_exactly_one():
    """Round 1 carries no drafts: the accept rule's degenerate case commits one token, so the drafter
    advances over one position — the chunk's own — and drafts from there."""
    tail = _RecordingTail()
    dr = DS.RingDrafter(tail)
    msg, out = _chunk([5, 6, 7], 0, token=42)              # the ring's prefill, as above
    dr.on_chunk(msg, _TapStage(3), out)
    tail.calls.clear()

    msg, out = _chunk([42], 7, tokens=[63])
    rep = dr.on_chunk(msg, _TapStage(1), out)
    assert rep == {"draft": [71, 72, 73], "n": 0, "conf": [0.5, 0.5, 0.5]}
    assert tail.calls == [("advance", [63], [0], 7)], "one committed position, its own tap, at pos 7"


@pytest.mark.parametrize("tokens,n,committed,taps", [
    ([7, 8, 55, 0], 2, [7, 8, 55], [0, 1, 2]),        # partial: drafts 7,8 accepted, 9 rejected
    ([90, 0, 0, 0], 0, [90], [0]),                    # nothing accepted: one correction, one tap
    ([7, 8, 9, 11], 3, [7, 8, 9, 11], [0, 1, 2, 3]),  # full accept + the bonus token
])
def test_ring_drafter_advances_over_the_committed_prefix(tokens, n, committed, taps):
    """THE slice that matters: the drafter is advanced over the ACCEPTED PREFIX of the round, never
    over the whole chunk.

    Feeding the chunk instead passes every check the drafter itself can make — a full accept commits
    g+1 positions, so length alone cannot tell them apart — and drafts off a continuation the ring
    threw away. Here the committed tokens and the taps' own position markers are both asserted, for
    every accept length a round can produce."""
    tail = _RecordingTail()
    dr = DS.RingDrafter(tail)
    msg, out = _chunk([1, 2], 0, token=42)
    dr.on_chunk(msg, _TapStage(2), out)
    tail.calls.clear()

    msg, out = _chunk([42, 7, 8, 9], 7, tokens=tokens)
    rep = dr.on_chunk(msg, _TapStage(4), out)
    assert rep["n"] == n and rep["draft"] == [71, 72, 73]
    assert tail.calls == [("advance", committed, taps, 7)]


def test_ring_drafter_refuses_what_it_cannot_answer():
    """Two refusals, both about a reply the protocol cannot express: a batch (the tail answers for row
    0 alone) and a dspark job whose reset forgot `spec` (no per-position tokens, hence no accept)."""
    dr = DS.RingDrafter(_RecordingTail())
    st = _TapStage(2)
    with pytest.raises(RuntimeError, match="single-sequence"):
        dr.on_chunk({"ids": [[1, 2], [3, 4]], "start_pos": 3}, st, {"token": 1, "tokens": [1, 2]})
    with pytest.raises(RuntimeError, match="must arm `spec`"):
        dr.on_chunk({"ids": [[1, 2]], "start_pos": 3}, st, {"token": 1})


def test_ring_drafter_degrades_to_greedy_at_the_context_limit():
    """The context cliff. `advance_and_draft` REFUSES to rope a block past max_seq_len — correct for
    the drafter, fatal for the ring, because an exception in the tail's serve loop takes the whole
    ring down with it and the coordinator (which only ever reads the tail) sees a stall. So the last
    rounds of a max-length generation stop drafting and keep answering, and once stopped they stay
    stopped: the drafter's cursor no longer tracks the stream."""
    tail = _RecordingTail(max_seq_len=20)
    dr = DS.RingDrafter(tail)
    msg, out = _chunk([1, 2], 0, token=42)
    dr.on_chunk(msg, _TapStage(2), out)
    tail.calls.clear()

    at = tail.args.max_seq_len - tail.block_size            # a block from here would rope past the end
    msg, out = _chunk([42, 7], at, tokens=[7, 8])
    rep = dr.on_chunk(msg, _TapStage(2), out)
    assert rep == {"draft": [], "n": 1}, "the accept still has to be reported — the ring commits it"
    assert tail.calls == [], "nothing may reach the drafter once it would raise"
    msg, out = _chunk([9], 1, tokens=[10])                 # and it stays stopped for the job
    rep = dr.on_chunk(msg, _TapStage(1), out)
    assert rep == {"draft": [], "n": 0} and tail.calls == []


# ── 7b. PIPELINED mode: the same accept rule, one streamed s=1 frame at a time ────────────────────


def _pframe(ids, start_pos, tokens=None, token=None):
    """One streamed frame + the reply the tail has already built for it (the model's greedy token at
    this frame's position), in RingDrafter.on_chunk's (msg, st, out) shape."""
    msg, out = _chunk(ids, start_pos, tokens=tokens, token=token)
    return msg, _TapStage(len(ids)), out


def _pipelined_drafter(prompt_len=4, first=99, **kw):
    """A pipelined RingDrafter with the ring's prefill already behind it. -> (drafter, tail)."""
    tail = _RecordingTail(**kw)
    dr = DS.RingDrafter(tail)
    dr.pipelined = True
    dr.on_chunk(*_pframe(list(range(prompt_len)), 0, token=first))
    tail.calls.clear()
    return dr, tail


def test_pipelined_prefill_seeds_the_frontier_and_drafts_nothing():
    """Identical to the serial prefill — the whole prompt's taps, no block — plus the one thing the
    streamed path needs from it: the frontier. The last prompt position is committed by construction
    and the reply's own token is the model's at the one after it, which is exactly what the first
    streamed frame will carry."""
    tail = _RecordingTail()
    dr = DS.RingDrafter(tail)
    dr.pipelined = True
    assert dr.on_chunk(*_pframe([5, 6, 7, 8], 0, token=99)) == {"acc": True}
    assert tail.calls == [("reset",), ("prefill", [99], [0, 1, 2, 3])]
    assert (dr._cfront, dr._mfront) == (3, 99)


def test_pipelined_committed_frame_advances_exactly_one_position_and_drafts():
    """A frame carrying the model's own token at the frontier is COMMITTED: the drafter advances over
    that one position, pairing this frame's tap with this frame's greedy reply, and the block it
    returns is the speculation the coordinator streams behind the token it is about to commit."""
    dr, tail = _pipelined_drafter(prompt_len=4, first=99)
    rep = dr.on_chunk(*_pframe([99], 4, tokens=[63]))
    assert rep == {"acc": True, "draft": [71, 72, 73], "conf": [0.5, 0.5, 0.5]}
    assert tail.calls == [("advance", [63], [0], 4)], "one position, its own tap, at the frontier"


def test_pipelined_rejects_a_speculative_frame_and_everything_streamed_behind_it():
    """THE INCREMENTAL ACCEPT RULE, including the part that is easy to get wrong.

    A frame whose token is not the model's at that position is speculative-and-wrong: it must not move
    the frontier and must not touch the drafter. Neither may ANY frame streamed behind it — and the
    frame behind it here carries exactly the greedy token the REJECTED frame produced, which is what a
    naive "does this match the last reply" rule would accept, drafting off a history the ring threw
    away. The frontier test (`q == cfront + 1`) is what refuses it. The coordinator's correction lands
    back AT the frontier with the model's own token, and re-opens."""
    dr, tail = _pipelined_drafter(prompt_len=4, first=99)
    dr.on_chunk(*_pframe([99], 4, tokens=[63]))                # committed: frontier 4, model says 63
    tail.calls.clear()
    assert dr.on_chunk(*_pframe([500], 5, tokens=[64])) == {"acc": False}, "a wrong draft"
    assert dr.on_chunk(*_pframe([64], 6, tokens=[65])) == {"acc": False}, "poisoned: behind a reject"
    assert tail.calls == [], "a speculative frame must never advance the drafter"
    rep = dr.on_chunk(*_pframe([63], 5, tokens=[77]))          # the correction, at the frontier
    assert rep["acc"] is True and tail.calls == [("advance", [77], [0], 5)]


def test_pipelined_refuses_a_multi_token_frame():
    """The whole point of the lever is that no stage replays a block position by position, so a
    pipelined frame is s=1 by construction and anything else is a coordinator bug."""
    dr, _tail = _pipelined_drafter()
    with pytest.raises(RuntimeError, match="streams s=1 frames"):
        dr.on_chunk(*_pframe([99, 7], 4, tokens=[63, 64]))


def test_pipelined_degrades_to_greedy_at_the_context_limit():
    """The context cliff, pipelined: stop drafting before a block would rope past max_seq_len, but
    keep judging frames — the frontier has to keep moving or the coordinator's next frame is refused.
    The run degrades to one frame in flight, which is plain greedy decode."""
    dr, tail = _pipelined_drafter(prompt_len=4, first=99, max_seq_len=20)
    at = tail.args.max_seq_len - tail.block_size               # a block from here ropes past the end
    dr._cfront, dr._mfront = at - 1, 99
    assert dr.on_chunk(*_pframe([99], at, tokens=[7])) == {"acc": True, "draft": []}
    assert tail.calls == [], "nothing may reach the drafter once it would raise"
    assert (dr._cfront, dr._mfront) == (at, 7), "the frontier still has to advance"
    assert dr.on_chunk(*_pframe([7], at + 1, tokens=[8])) == {"acc": True, "draft": []}


def test_pipelined_stepwise_advance_equals_one_multiposition_advance(oracle, args):
    """The decomposition the pipelined drafter rests on: advancing ONE position per streamed frame is
    bit-identical to the serial round's single call over the whole committed run.

    It has to be, and not merely "close": if the two cadences produced different mtp state, the two
    coordinators would propose different blocks off the same history, and every acceptance measurement
    taken on one path would say nothing about the other. `advance_and_draft` loops per position
    internally and keeps the last block, so this is really the assertion that the loop has no state
    outside the drafter — proven on two independent drafters prefilled from the same tensors."""
    ids = _ids(PROMPT, args, seed=LOOP_SEED)
    st, serial, tok = prefilled(oracle, args, ids)
    main0 = st.tail_main_hidden()                              # the prompt's taps, still the last forward
    _st_b, streamed = tail_from_oracle(oracle, args)
    streamed.prefill(tok, main0)

    forced = [torch.full((BATCH,), t, dtype=torch.long) for t in (7, 151, 293)[:RUN]]
    toks = [tok] + forced
    chunk = torch.cat([t.unsqueeze(1) for t in toks[:RUN]], dim=1)
    h = st.forward(st.embed(chunk), chunk, PROMPT)
    main = st.tail_main_hidden()
    committed = torch.cat([t.unsqueeze(1) for t in toks[1:]], dim=1)

    d_serial, c_serial = serial.advance_and_draft(committed, main, start_pos=PROMPT)
    for j in range(RUN):                                       # the pipelined cadence: one at a time
        d_stream, c_stream = streamed.advance_and_draft(committed[:, j:j + 1], main[:, j:j + 1],
                                                        start_pos=PROMPT + j)
    assert serial.pos == streamed.pos == PROMPT + RUN - 1
    assert torch.equal(d_serial, d_stream), "the block differs between the two cadences"
    assert torch.equal(c_serial, c_stream), "the confidence differs between the two cadences"
    for k, (a, b) in enumerate(zip(caches(serial), caches(streamed))):
        assert torch.equal(a, b), f"mtp stage {k} cache differs between the two cadences"


def test_ring_drafter_over_the_real_drafter(oracle, args):
    """The same adapter, over a real Stage + DSparkTail: one drafted round, graded on the oracle.

    The recorder above proves the slices; this proves they are the slices the REFERENCE wants. The
    ring's own reply is assembled by hand (a chunk of one, the tail's greedy token) so the assertion
    is about RingDrafter and not about v4_pipe's serve loop."""
    ids = _ids(PROMPT, args, seed=LOOP_SEED)
    st, dr_tail, tok = prefilled(oracle, args, ids)
    o_tok, _, o_main = oracle(tok.unsqueeze(1), PROMPT)
    o_spec = oracle.forward_spec(o_tok, o_main, PROMPT)

    ring = DS.RingDrafter(dr_tail)
    h = st.forward(st.embed(tok.unsqueeze(1)), tok.unsqueeze(1), PROMPT)
    reply = int(st.logits_all(h, full_logits=False).argmax(-1))
    rep = ring.on_chunk({"ids": [[int(tok)]], "start_pos": PROMPT}, st,
                        {"token": reply, "tokens": [reply]})
    assert rep["n"] == 0, "a bare round accepts nothing and commits the model's own token"
    assert rep["draft"] == o_spec[0][0, 1:].tolist(), "the block is not the reference's"
    assert dr_tail.pos == PROMPT


def test_spec_loop_with_a_perfect_drafter(oracle, args):
    """Same loop, drafts replaced by the true continuation: full accepts, bonus token, no rewind.

    A random-weight drafter proposes almost nothing acceptable, so the real loop above only ever
    exercises n = 0. This one forces n = block_size every round -- the multi-position advance, the
    full-accept bonus, and the case where the chunk the stage consumed happens to be exactly what
    was committed. Both loops must emit the same greedy stream."""
    ids, want = _rich_ids(args, GEN + args.dspark_block_size + 1)
    g = args.dspark_block_size

    def perfect(_):
        return want[len(perfect.out) : len(perfect.out) + g]
    perfect.out = []

    st, dr, tok = prefilled(oracle, args, ids)
    out, accepted = [int(tok)], []
    drafts = []
    while len(out) < GEN:
        p = ids.shape[1] + len(out) - 1
        chunk = torch.tensor([[out[-1]] + list(drafts)], dtype=torch.long)
        h = st.forward(st.embed(chunk), chunk, p)
        replies = [int(st.logits_all(h[:, j:j + 1], full_logits=False).argmax(-1))
                   for j in range(chunk.shape[1])]
        n, committed = DS.plan_verify_round(drafts, replies)
        assert n == len(drafts), f"a perfect draft must be fully accepted, got {n}/{len(drafts)}"
        assert len(committed) == n + 1, "a full accept still commits the bonus token"
        taps = st.tail_main_hidden()[:, :n + 1]
        out.extend(committed)
        accepted.append(n)
        dr.advance_and_draft(torch.tensor([committed], dtype=torch.long), taps, start_pos=p)
        assert dr.pos == p + n and st._pos == p + n + 1, "a full accept needs no stage rewind"
        perfect.out = out
        drafts = perfect(None)
    assert out == want[:len(out)]
    assert max(accepted) == g, "the perfect drafter never reached a full block"


