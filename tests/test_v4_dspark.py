def test_plan_verify_round():
    """Longest matching prefix + the correction, and the bonus token on a full accept."""
    assert DS.plan_verify_round([1, 2, 3], [1, 2, 3, 9]) == (3, [1, 2, 3, 9])   # full + bonus
    assert DS.plan_verify_round([1, 2, 3], [1, 7, 3, 9]) == (1, [1, 7])         # partial
